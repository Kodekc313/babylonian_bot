def generate_artifact_description() -> str:
    """Генерирует описание мистического артефакта."""
    form = random.choice(ARTIFACT_FORMS)
    material = random.choice(ARTIFACT_MATERIALS)
    prop1 = random.choice(ARTIFACT_PROPERTIES)
    prop2 = random.choice(ARTIFACT_PROPERTIES)
    # Убедимся, что свойства разные
    while prop1 == prop2:
        prop2 = random.choice(ARTIFACT_PROPERTIES)

    return f"Это {form} из {material}. Предмет {prop1} и {prop2}."

def calculate_numerology(text: str) -> tuple[int, str]:
    """Рассчитывает нумерологическое число слова (простой метод) и дает краткую трактовку."""
    text = text.lower()
    total = 0
    # Простая система: a=1, b=2, ... z=26 (игнорируем другие символы)
    # Для русского алфавита можно сделать свою таблицу соответствия
    for char in text:
        if 'a' <= char <= 'z':
            total += ord(char) - ord('a') + 1
        elif 'а' <= char <= 'я': # Добавим русский алфавит
             # Простейшее соответствие по порядку (не канонично!)
             total += ord(char) - ord('а') + 1

    # Сводим к одной цифре (если не 11, 22, 33 - мастер-числа)
    final_num = total
    while final_num > 9 and final_num not in [11, 22, 33]:
        final_num = sum(int(digit) for digit in str(final_num))

    # Простые трактовки (можно сильно расширить)
    interpretations = {
        1: "Лидерство, Начало, Независимость.",
        2: "Партнерство, Дипломатия, Двойственность.",
        3: "Творчество, Общение, Оптимизм.",
        4: "Стабильность, Порядок, Труд.",
        5: "Свобода, Перемены, Любопытство.",
        6: "Гармония, Забота, Ответственность.",
        7: "Мудрость, Анализ, Уединение.",
        8: "Сила, Амбиции, Материальный успех.",
        9: "Завершение, Гуманизм, Прощение.",
        11: "Интуиция, Вдохновение, Духовность (Мастер-число).",
        22: "Созидание, Мастерство, Глобальные цели (Мастер-число).",
        33: "Служение, Исцеление, Учитель (Мастер-число)."
    }
    interpretation = interpretations.get(final_num, "Неопределенная вибрация...")

    return final_num, interpretation

