# --- Функции генерации ---
def generate_mystic_phrase() -> str:
    # ... (код не изменился, оставляем как есть) ...
    phrase_structure = random.choice([1, 2, 3])
    phrase = ""
    if phrase_structure == 1:
        phrase = f"{random.choice(ADJECTIVES).capitalize()} {random.choice(NOUNS)} {random.choice(VERBS)} {random.choice(ADJECTIVES)} {random.choice(NOUNS)} {random.choice(LOCATIONS)}..."
    elif phrase_structure == 2:
        phrase = f"Внемли: {random.choice(NOUNS)} {random.choice(VERBS)} {random.choice(LOCATIONS)}, где {random.choice(ADJECTIVES)} {random.choice(NOUNS)} ждет..."
    else:
        phrase = f"Знай, {random.choice(LOCATIONS)} {random.choice(VERBS)} {random.choice(ADJECTIVES)} {random.choice(NOUNS)}... {random.choice(MYSTIC_SYMBOLS)}"

    if random.random() < 0.15: # 15% шанс добавить помеху
        phrase += f" ... {random.choice(['шшш...', '...помехи...', 'сигнал утерян...', 'они слушают...', '👁️'])}"
    return phrase

def generate_sigil_text(length: int = 7) -> str:
    # ... (код не изменился, оставляем как есть) ...
    if length < 3: length = 3
    if length > 15: length = 15
    return "".join(random.choices(MYSTIC_SYMBOLS, k=random.randint(length - 2, length + 2)))

